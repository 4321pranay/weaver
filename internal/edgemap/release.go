// ReleaseFile is releases.yaml: each service's
// releases, newest first (spec §12).
type ReleaseFile struct {
	Version  string            `yaml:"version"`
	Run      string            `yaml:"run"`
	BuiltAt  string            `yaml:"builtAt"`
	Services []ServiceReleases `yaml:"services"`
}

type ServiceReleases struct {
	ServiceName string    `yaml:"serviceName"`
	Releases    []Release `yaml:"releases,omitempty"`
}

type Release struct {
	Version    string `yaml:"version,omitempty"`
	CommitHash string `yaml:"commitHash"`
	BuiltAt    string `yaml:"builtAt"`
	Edges      string `yaml:"edges,omitempty"` // snapshot in edges.history/<svc>/<edges>.yaml
	// GitURL is set on the oldest release kept and wherever the repo moved;
	// a release without it has the same repo as the release before it
	GitURL string `yaml:"gitUrl,omitempty"`
}

// Record writes releases.yaml and the per-service edge snapshots for one
// domain's build. Call it after edges.yaml is written. A service without a git
// commit (a plain directory) has no release to record and is listed as such.
func Record(releasesPath, historyDir string, built []snapshot.Manifest, sourceDir func(svc string) string, m Map, now time.Time) (notes []string, err error) {
	var prev ReleaseFile
	if b, err := os.ReadFile(releasesPath); err == nil {
		if err := yaml.Unmarshal(b, &prev); err != nil {
			return nil, fmt.Errorf("%s: %w", releasesPath, err)
		}
	}
	old := map[string][]Release{}
	for _, s := range prev.Services {
		old[s.ServiceName] = s.Releases
	}
	ts := now.UTC().Format(time.RFC3339)
	w := ReleaseFile{Version: FormatReleases, Run: m.Run, BuiltAt: ts}
	keep := map[string]bool{}
	for _, b := range built {
		src := ServiceReleases{ServiceName: b.ServiceName, Releases: old[b.ServiceName]}
		keep[b.ServiceName] = true
		if b.SHA == "" || b.SHA == "nogit" {
			notes = append(notes, b.ServiceName+": not a git checkout, no release recorded")
			w.Services = append(w.Services, src)
			continue
		}
		// a release is its build-file version (build-spec §2): a new commit with the
		// same version updates that release; a new version starts one. Every
		// release is kept.
		v := ReleaseVersion(sourceDir(b.ServiceName))
		if v == "" {
			notes = append(notes, fmt.Sprintf("%s: no release version for %.12s (no version in its build file or version.json)", b.ServiceName, b.SHA))
		}
		switch {
		case len(src.Releases) > 0 && src.Releases[0].CommitHash == b.SHA:
			// rebuilt at the same commit: history untouched
		case len(src.Releases) > 0 && v != "" && src.Releases[0].Version == v:
			src.Releases[0].CommitHash, src.Releases[0].BuiltAt = b.SHA, ts
		default:
			src.Releases = append([]Release{{Version: v, CommitHash: b.SHA, BuiltAt: ts, GitURL: b.GitURL}}, src.Releases...)
		}
		sparseURLs(src.Releases)
		if err := snapshotEdges(&src, filepath.Join(historyDir, b.ServiceName), m); err != nil {
			return nil, err
		}
		w.Services = append(w.Services, src)
	}
	// a service gone from sources.yaml leaves releases.yaml; its edge history
	// stays, as older builds still describe it (build-spec §2)
	_ = keep
	b, err := yaml.Marshal(w)
	if err != nil {
		return nil, err
	}
	head := "# Generated by weaver build (docs/build-spec.md §2). Do not edit.\n"
	return notes, writeAtomic(releasesPath, append([]byte(head), b...))
}

// snapshotEdges keeps the service's edge snapshot for its newest release: a
// new file only when its edges changed (build-spec §3). Every snapshot is kept;
// a release whose version gets a new commit with other edges rewrites its own.
func snapshotEdges(src *ServiceReleases, dir string, m Map) error {
	cur := serviceMap(m, src.ServiceName)
	files, _ := filepath.Glob(filepath.Join(dir, "*.yaml"))
	sort.Slice(files, func(i, j int) bool { return modTime(files[i]).After(modTime(files[j])) })
	r := &src.Releases[0]
	if len(files) > 0 {
		var newest Map
		if b, err := os.ReadFile(files[0]); err == nil && yaml.Unmarshal(b, &newest) == nil && signature(newest) == signature(cur) {
			r.Edges = strings.TrimSuffix(filepath.Base(files[0]), ".yaml")
			return nil
		}
	}
	name := r.Version
	if name == "" {
		name = r.CommitHash[:min(12, len(r.CommitHash))]
	}
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	b, err := yaml.Marshal(cur)
	if err != nil {
		return err
	}
	if err := writeAtomic(filepath.Join(dir, name+".yaml"), b); err != nil {
		return err
	}
	r.Edges = name
	return nil
}

// serviceMap: the edges whose code is in svc (its outgoing edges, and the
// consume edges ending at it) with the nodes they use (spec §12.3).
func serviceMap(m Map, svc string) Map {
	out := Map{Version: FormatEdges, Run: m.Run, Nodes: []Node{}, Edges: []Edge{}}
	used := map[string]bool{}
	for _, e := range m.Edges {
		if e.From == svc || (e.To == svc && inbound[e.Op]) {
			out.Edges = append(out.Edges, e)
			used[e.From], used[e.To] = true, true
		}
	}
	for _, n := range m.Nodes {
		if used[n.ID] {
			out.Nodes = append(out.Nodes, n)
		}
	}
	return out
}

// signature: what counts as a change (spec §12.3): the set of edges with
// their from, to, kind, resource, op and call. Line numbers don't count.
func signature(m Map) string {
	var rows []string
	for _, e := range m.Edges {
		rows = append(rows, strings.Join([]string{e.From, e.To, e.Kind, e.Resource, e.Op, e.Call}, "\x00"))
	}
	sort.Strings(rows)
	return strings.Join(rows, "\n")
}

var (
	reGradleVersion = regexp.MustCompile(`(?m)^\s*version\s*=?\s*['"]([^'"$]+)['"]`)
)

// releaseVersion (build-spec §2.1): the service's build file only: Maven
// <version>, Gradle version, else version.json ({"version": "1.4.0"}). Git tags
// are never used. "" when none: a version is never invented.
func ReleaseVersion(dir string) string {
	if b, err := os.ReadFile(filepath.Join(dir, "pom.xml")); err == nil {
		var pom struct {
			Version string `xml:"version"` // the project's own, not a dependency's or the parent's
		}
		if xml.Unmarshal(b, &pom) == nil && pom.Version != "" && !strings.Contains(pom.Version, "$") {
			return strings.TrimSpace(pom.Version)
		}
	}
	for _, f := range []string{"build.gradle", "build.gradle.kts", "gradle.properties"} {
		if b, err := os.ReadFile(filepath.Join(dir, f)); err == nil {
			if m := reGradleVersion.FindSubmatch(b); m != nil {
				return string(m[1])
			}
		}
	}
	if b, err := os.ReadFile(filepath.Join(dir, "version.json")); err == nil {
		var v struct {
			Version string `json:"version"`
		}
		if json.Unmarshal(b, &v) == nil && v.Version != "" {
			return strings.TrimSpace(v.Version)
		}
	}
	return ""
}

func modTime(p string) time.Time {
	if st, err := os.Stat(p); err == nil {
		return st.ModTime()
	}
	return time.Time{}
}

func writeAtomic(path string, b []byte) error {
	tmp := path + ".tmp"
	if err := os.WriteFile(tmp, b, 0o644); err != nil {
		return err
	}
	return os.Rename(tmp, path)
}

// RunID identifies a build by what it built: every service's git URL and
// commit. The same sources always give the same id; any service at another
// commit gives a new one. A plain directory (no git) counts as "nogit".
func RunID(built []snapshot.Manifest) string {
	rows := make([]string, 0, len(built))
	for _, b := range built {
		rows = append(rows, b.GitURL+"@"+b.SHA)
	}
	sort.Strings(rows)
	h := sha1.Sum([]byte(strings.Join(rows, "\n")))
	return fmt.Sprintf("run-%x", h[:6])
}

// sparseURLs keeps gitUrl only where it tells something: on the oldest
// release, and on any release whose repo differs from the one before it.
func sparseURLs(rs []Release) {
	url := ""
	for i := len(rs) - 1; i >= 0; i-- { // oldest first: carry the repo forward
		if rs[i].GitURL == "" {
			rs[i].GitURL = url
		}
		url = rs[i].GitURL
	}
	for i := 0; i < len(rs)-1; i++ {
		if rs[i].GitURL == rs[i+1].GitURL {
			rs[i].GitURL = ""
		}
	}
}
